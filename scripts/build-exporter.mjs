import { readFile, writeFile } from 'node:fs/promises'
import ts from 'typescript'
// Bundle only the shared, platform-neutral collection module. The terminal wrapper adds no provider reads.
const modules = await Promise.all(['pagerduty', 'opsgenie', 'bundle'].map(name => readFile(`src/move-in/collect/${name}.ts`, 'utf8')))
const shared = modules.map(source => source.replace(/^import .* from ['"].*['"]\s*$/gm, '')).join('\n')
const javascript = ts.transpileModule(shared, { compilerOptions: { target: ts.ScriptTarget.ES2023, module: ts.ModuleKind.ESNext } }).outputText
const cli = await readFile('scripts/exporter-cli.mjs', 'utf8')
await writeFile('public/move-in/oncall-export.mjs.txt', '#!/usr/bin/env node\n// Generated by scripts/build-exporter.mjs from src/move-in/collect/. Do not edit.\n' + javascript + '\n' + cli)
console.log('Generated the standalone exporter from the app collection module.')
