import assert from 'node:assert/strict';
import {randomBytes,randomUUID} from 'node:crypto';
import {autonomousPolicy} from '../src/modules/agent-door/conformance/crypto.mjs';

/** Real MCP, signed policy, native review, team CAS and subject-erasure doors. */
export async function teamReplay(runtime) {
 const {http,tool,adopt,db}=runtime;
 const code=answer=>answer.result?._meta?.['com.runeditrun/error']?.code??answer.body?.error?.data?.code;
 const state=async()=> (await (await http('/api/state')).json());
 assert.equal((await adopt()).status,200);
 const password=randomBytes(32).toString('hex');
 const other=await (await http('/api/members',{name:'Team receipt authority administrator',role:'admin',password})).json();
 const manager=await (await http('/api/members',{name:'Team receipt responder',role:'responder',password:randomBytes(32).toString('hex')})).json();
 const owner=(await (await http('/api/workspace')).json()).member;
 const created=await http('/api/teams',{revision:0,name:'Receipt coordination team',visibility:'public',active:true,members:[owner.id,manager.id],managers:[]});
 assert.equal(created.status,200);
 const team=await created.json();
 const args={...team,name:'Reviewed manager authority',managers:[manager.id],idempotency_key:randomUUID()};
 await db.exec("CREATE TRIGGER refuse_team_receipt BEFORE INSERT ON oc_agent_team_receipts BEGIN SELECT RAISE(ABORT,'receipt storage unavailable'); END");
 const before=await state(),failed=await tool('oncall.teams.update',args);
 assert.ok(failed.result?.isError||failed.body?.error);
 assert.equal(failed.result?.structuredContent,undefined);
 assert.deepEqual(await state(),before,'A receipt failure rolls back the team and native audit');
 assert.equal((await db.prepare('SELECT COUNT(*) AS n FROM oc_agent_team_receipts').first()).n,0);
 await db.exec('DROP TRIGGER refuse_team_receipt');
 args.idempotency_key=randomUUID();
 const held=autonomousPolicy();held.rules.unshift({id:'team-access-review',class:'access',do:'approval',approver:['sponsor'],wait:'PT1H'});
 assert.equal((await adopt(held)).status,200);
 const pending=await tool('oncall.teams.update',args),approval=pending.result?._meta?.['com.runeditrun/approval'];
 assert.ok(approval,JSON.stringify(pending.body));
 const saved=(await (await http('/agents/api/approvals/'+approval.id)).json()).approval;
 assert.equal((await http('/agents/api/approvals/'+approval.id+'/approve',{revision:saved.revision,summary_sha256:'0'.repeat(64)})).status,409);
 assert.deepEqual(await state(),before,'Only the exact reviewed digest may execute');
 const approved=await http('/agents/api/approvals/'+approval.id+'/approve',{revision:saved.revision,summary_sha256:saved.summary_sha256});
 assert.equal((await approved.json()).approval.state,'executed');
 const once=await state(),first=await tool('oncall.teams.update',args),again=await tool('oncall.teams.update',args);
 assert.equal(first.result?.isError,false,JSON.stringify(first.body));
 assert.equal(first.result.structuredContent.revision,team.revision+1);
 assert.deepEqual(first.result.structuredContent.managers,[manager.id]);
 assert.deepEqual(again.result.structuredContent,first.result.structuredContent);
 const receipt=first.result._meta['com.runeditrun/receipt'];
 assert.equal(receipt.approval_id,approval.id);
 assert.equal(receipt.id,again.result._meta['com.runeditrun/receipt'].id);
 assert.deepEqual(first.decision.classes.map(({class:risk,facts})=>({class:risk,facts})),[{class:'access',facts:{measure:1,direction:'widens'}}]);
 assert.deepEqual(await state(),once,'Completed team replay has no second native effect');
 const rows=(await db.prepare('SELECT * FROM oc_agent_team_receipts').all()).results;
 assert.equal(rows.length,1);assert.equal(rows[0].approval,approval.id);
 assert.deepEqual(JSON.parse(rows[0].manager_gains),[manager.id]);
 for(const value of [team.name,args.name,args.idempotency_key,manager.name])assert.ok(!JSON.stringify(rows).includes(value),'Custody holds binding IDs and digests without names, arguments or cached results');
 assert.equal(code(await tool('oncall.teams.update',{...args,idempotency_key:randomUUID()})),'revision_conflict');
 assert.equal(code(await tool('oncall.teams.update',{...args,name:'Changed reviewed input'})),'idempotency_conflict');
 assert.equal(code(await tool('oncall.teams.update',args,{scope:'incidents:read'})),'insufficient_scope');
 assert.equal(code(await tool('oncall.teams.update',args,{consent:randomUUID()})),'idempotency_conflict');
 assert.equal(code(await tool('oncall.teams.update',args,{client_id:randomUUID()})),'idempotency_conflict');
 assert.equal((await http('/agents/api/pause',{paused:true})).status,200);
 assert.equal(code(await tool('oncall.teams.update',args)),'agents_paused');
 assert.equal((await http('/agents/api/pause',{paused:false})).status,200);
 assert.equal((await adopt(held,{revoked:{agents:[],consents:[runtime.context.consent]}})).status,200);
 assert.equal((await tool('oncall.teams.update',args)).status,401);
 assert.equal((await adopt(held,{paused:true})).status,200);
 assert.equal(code(await tool('oncall.teams.update',args)),'agents_paused');
 assert.equal((await adopt(held)).status,200);
 assert.deepEqual(await state(),once,'Refused replays leave the committed native effect unchanged');
 // A later native edit cannot borrow the older committed effect's review.
 assert.equal((await http('/api/teams',{...first.result.structuredContent,name:'Later native team revision'})).status,200);
 assert.equal(code(await tool('oncall.teams.update',args)),'revision_conflict');
 const login=await http('/api/login',{name:other.name,password});assert.equal(login.status,200);
 const cookie=login.headers.getSetCookie().map(value=>value.split(';',1)[0]).join('; ');await login.body?.cancel();
 assert.equal((await http('/api/command',{type:'member',id:owner.id,role:'viewer',active:true})).status,200);
 const demoted=await tool('oncall.teams.update',args);assert.equal(demoted.status,401);assert.equal(demoted.result?.structuredContent,undefined);
 const restore=await runtime.request(runtime.origin+'/api/command',{method:'POST',headers:{Origin:runtime.origin,Cookie:cookie,'Content-Type':'application/json'},body:JSON.stringify({type:'member',id:owner.id,role:'admin',active:true})});
 assert.equal(restore.status,200);await restore.body?.cancel();
 const erased=await http('/api/erasure/member/'+manager.id,{workspaceRevision:(await state()).revision,confirmation:'erase '+manager.id,identitiesReviewed:true,importedPeople:[]});
 assert.equal(erased.status,200);
 assert.equal((await db.prepare('SELECT COUNT(*) AS n FROM oc_agent_team_receipts').first()).n,0,'Native subject erasure clears team replay custody');
 assert.equal((await adopt()).status,200);
 console.log('PASS team-manager receipts: atomic team/audit rollback, exact review, original facts/approval and one-effect replay; changed key/arguments, scopes, consent, client, Pause, later revision and owner demotion refused; native erasure clears custody');
}
